print('PBZ_NATIVE_INPUT:START\n')
ExecuteWithDelay(1500,function()
    local ok,why=pcall(function()
        assert(type(PBZNativeCombatInputSnapshot)=='function','native helper not registered')
        local a=PBZNativeCombatInputSnapshot()
        assert(a.schema==1 and math.type(a.pid)=='integer'and a.pid>0 and type(a.now)=='number')
        assert(a.allowed==false and a.down==false,'headless lab must never own gameplay input')
        local b=PBZNativeCombatInputSnapshot()
        assert(b.pid==a.pid and b.now>=a.now,'native monotonic snapshot changed process')
        print('PBZ_NATIVE_INPUT:BACKGROUND=true|MONOTONIC=true|PID='..a.pid..'\n')
        print('PBZ_NATIVE_INPUT:PASS\n')
    end)
    if not ok then print('PBZ_NATIVE_INPUT:FAIL='..tostring(why)..'\n')end
end)
