 if os.time()>=deadline then emit('PBZ_BOSS_META','STOP','deadline');return true end
 if next_item>#requests then
  emit('PBZ_MULTI_ID','END','62359a4091381b58')
  emit('PBZ_BOSS_META','END','62359a4091381b58');return true
 end
